import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "node_modules/katex/dist/katex.min.css");
const target = resolve(root, "src/features/markdown/katex-css.ts");

const css = readFileSync(source, "utf8");
writeFileSync(
  target,
  `/* Generated by scripts/generate-katex-css.mjs. Do not edit by hand. */\nexport const katexCss = ${JSON.stringify(css)};\n`,
  "utf8",
);

console.log(`Generated ${target}`);
